import { type ViewportOptions } from "framer-motion";

/* -------------------------------------------------------------------------- */
/*                              Viewport Factory                              */
/* -------------------------------------------------------------------------- */

const createViewport = (
  amount: number,
  once = true,
): ViewportOptions => ({
  once,
  amount,
});

/* -------------------------------------------------------------------------- */
/*                               Base Viewport                                */
/* -------------------------------------------------------------------------- */

export const viewport = createViewport(0.2);

/* -------------------------------------------------------------------------- */
/*                           Hero / Above the Fold                            */
/* -------------------------------------------------------------------------- */

export const heroViewport = createViewport(0.05);

/* -------------------------------------------------------------------------- */
/*                             Large Sections                                 */
/* -------------------------------------------------------------------------- */

export const sectionViewport = createViewport(0.15);

/* -------------------------------------------------------------------------- */
/*                               Cards / Grid                                 */
/* -------------------------------------------------------------------------- */

export const cardViewport = createViewport(0.25);

/* -------------------------------------------------------------------------- */
/*                                  Images                                    */
/* -------------------------------------------------------------------------- */

export const imageViewport = createViewport(0.3);

/* -------------------------------------------------------------------------- */
/*                            Decorative Elements                             */
/* -------------------------------------------------------------------------- */

export const repeatViewport = createViewport(0.25, false);

/* -------------------------------------------------------------------------- */
/*                          Nearly Fully Visible                              */
/* -------------------------------------------------------------------------- */

export const fullViewport = createViewport(0.8);

/* -------------------------------------------------------------------------- */
/*                           Early Scroll Trigger                             */
/* -------------------------------------------------------------------------- */

export const earlyViewport = createViewport(0.1);

/* -------------------------------------------------------------------------- */
/*                            Late Scroll Trigger                             */
/* -------------------------------------------------------------------------- */

export const lateViewport = createViewport(0.45);

/* -------------------------------------------------------------------------- */
/*                               Export Default                               */
/* -------------------------------------------------------------------------- */

export const defaultViewport = viewport;